s = s.replace("（v10.14.1）", "（v10.14.2）")
s = s.replace(
    "版本：2026-08-12（v10.14.1，多进程采集架构 + 双系统兼容 + 防重复启动）",
    "版本：2026-08-12（v10.14.2，多进程采集架构 + 双系统兼容 + 防重复启动 + 黑屏/录制失败诊断）")
s = s.replace("VideoRec_win7_v10.14.1.zip", "VideoRec_win7_v10.14.2.zip")

NEW = """## 三、v10.14.2 更新内容

**1. 录制失败原因分层（治"所有摄像头均无法录制"）：**
- 之前只报"磁盘不可写？"，无法区分是目录不可写还是编码器问题。
- 现在先做目录写探针：目录不可写 → 报具体错误（含系统原因）；目录可写但 VideoWriter 打开失败 → 报"疑似编码器/文件名问题"。

**2. 黑屏诊断（治"摄像头无画面且无报错"）：**
- 采集子进程：摄像头就绪后持续 5 秒读不到帧 → 写入 capture_worker.log。
- 主界面：预览持续 5 秒无新帧 → 该路标签显示"已连接但无画面（驱动/带宽问题）" + 写入 videorec_error.log。
- 之前黑屏是静默的（无任何日志），现在有迹可查。

**3. 新增现场诊断工具 VideoRecDiag.exe：**
- 双击运行（约 30 秒），自动检查：磁盘可写性 / ffmpeg 编码器加载 / 视频写入矩阵 / 两路摄像头直开耗时。
- 结果写入同目录 diag_report.txt，发回即可定位问题。

## 四、v10.14.1 更新内容（历史）

**1. 防重复启动（单实例锁）：**
- 原因：摄像头打开期间界面不会立即出画面（Win7 上 USB 摄像头打开可能需要 1-2 分钟），容易被误认为卡死而重复双击 → 多个程序实例抢同一摄像头 → 谁也打不开。
- 解决：同一时间只允许运行一个实例。重复双击会提示"VideoRec 已在运行中"，不再多开。

**2. 打开进度显示 + 失败原因落盘：**
- 状态栏实时显示"已等待 N 秒 / 上限 180 秒"，界面标签提示"可能需要 1-2 分钟"，避免误判卡死。
- 摄像头打开失败/超时/进程退出的具体原因现在会写入 videorec_error.log（之前只显示在界面标签上，日志里查不到）。
- 摄像头未就绪时点录制，会明确提示"摄像头正在打开中，请等待画面出现"（之前只提示"摄像头未连接"，容易误解）。

## 五、v10.14 更新内容（历史）
"""
